// Reads the filled-in coordinate template (data-entry/poi-coordinates.csv) and regenerates
// app/data/poiCoords.ts. Only rows with BOTH a numeric lat and lng are written, so a
// half-filled template is fine — you can geocode a few counties at a time and re-run this.
//
//   node scripts/apply-poi-coords.mjs
//
// Columns expected: county,type,id,name,lat,lng  (only id, lat, lng are used)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const CSV = join(root, "data-entry", "poi-coordinates.csv");
const OUT = join(root, "src", "features", "map-explorer", "data", "poiCoords.ts");

/** Minimal CSV row parser (handles quoted fields with commas / doubled quotes). */
function parseRow(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') { cur += '"'; i++; } else { inQuotes = false; }
      } else cur += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const text = readFileSync(CSV, "utf8").replace(/\r\n/g, "\n").trim();
const lines = text.split("\n");
const header = parseRow(lines[0]).map((h) => h.trim().toLowerCase());
const col = (name) => header.indexOf(name);
const idI = col("id"), latI = col("lat"), lngI = col("lng");
if (idI < 0 || latI < 0 || lngI < 0) {
  throw new Error("CSV must have id, lat and lng columns");
}

const entries = [];
let skipped = 0;
for (let i = 1; i < lines.length; i++) {
  if (!lines[i].trim()) continue;
  const cells = parseRow(lines[i]);
  const id = (cells[idI] ?? "").trim();
  const latRaw = (cells[latI] ?? "").trim();
  const lngRaw = (cells[lngI] ?? "").trim();
  if (!id) continue;
  // A blank lat or lng means "not geocoded yet" — skip it (Number("") is 0, so guard explicitly).
  if (latRaw === "" || lngRaw === "") { skipped++; continue; }
  const lat = Number(latRaw);
  const lng = Number(lngRaw);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) { skipped++; continue; }
  entries.push([id, lat, lng]);
}

entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = entries.map(([id, lat, lng]) => `  ${JSON.stringify(id)}: [${lat}, ${lng}],`).join("\n");
const out = `// Coordinates for the seed POIs, kept separate from croatiaData.ts so the (large) POI list
// stays readable and the geocoding work can be filled in incrementally.
//
// GENERATED by scripts/apply-poi-coords.mjs from data-entry/poi-coordinates.csv — do not edit by hand.
// Fill the CSV's lat/lng columns and re-run the script to update this file.
//
//   key   = POI id (matches an \`id\` in the POIS array)
//   value = [lat, lng]  (decimal degrees, WGS84)

export const POI_COORDS: Record<string, [number, number]> = {
${body || "  // (none yet — fill data-entry/poi-coordinates.csv)"}
};
`;

writeFileSync(OUT, out);
console.log(`Wrote ${entries.length} coordinate(s) to src/features/map-explorer/data/poiCoords.ts` + (skipped ? ` (${skipped} row(s) still blank)` : ""));
